// Developer-only traffic numbers (?debug=true): extra rows for the tile
// inspector and city-wide totals for the tuning panel. English only on
// purpose — this is a balancing tool, not player-facing UI.

import type { World } from '../sim/World';
import { ROAD_NONE, ROAD_HIGHWAY, ZONE_NONE, ZONE_R, ZONE_C, ZONE_I } from '../sim/constants';
import { BALANCE } from '../data/balance';
import { bestAccessRoad, neighbourIndex, roadCapacity, trafficVolume } from '../sim/TrafficData';

const fmt = (v: number, digits = 1) => (v < Infinity ? v.toFixed(digits) : '∞');
const row = (text: string, color = '#9ad') => `<div class="ti-detail" style="color:${color}">${text}</div>`;

/** Extra inspector rows for the tile at index `i` ('' if there is nothing to say). */
export function trafficDebugHtml(world: World, i: number): string {
  const d = world.traffic;
  const L = world.layers;
  const road = L.roadClass[i];
  const zone = L.zone[i];
  if (road === ROAD_NONE && zone === ZONE_NONE) return '';

  let html = `<div class="ti-growth-header" style="color:#9ad">Traffic (debug)</div>`;
  if (!d) return html + row('No traffic pass yet — unpause for a moment.');
  const T = BALANCE.transit;

  if (road !== ROAD_NONE) {
    const vol = trafficVolume(d, i);
    const cap = roadCapacity(road);
    html += row(`Trips ${fmt(vol)} / ${cap} capacity = ${Math.round(vol / cap * 100)}%`);
    html += row(`To commerce: homes ${fmt(d.volRC[i])}, industry ${fmt(d.volIC[i])}`);
    html += row(`To industry: homes ${fmt(d.volRI[i])}`);
    html += row(`Time to commerce ${fmt(d.toC.dist[i])} · industry ${fmt(d.toI.dist[i])} · homes ${fmt(d.toR.dist[i])}`);
    if (road === ROAD_HIGHWAY) html += row('Highway: carries traffic, gives zones no access', '#999');
    return html;
  }

  const dev = L.devLevel[i];
  const access = L.accessibility[i];
  html += row(`Accessibility ${access}/255 (${Math.round(access / 255 * 100)}%)`);

  const timeVia = (field: typeof d.toC) => {
    const r = bestAccessRoad(world, i, field);
    return r >= 0 ? field.dist[r] : Infinity;
  };
  if (zone === ZONE_R) {
    html += row(`Commute: commerce ${fmt(timeVia(d.toC))} · industry ${fmt(timeVia(d.toI))} (limit ${T.commuteMax})`);
    if (dev > 0) html += row(`Sends ${fmt(dev * T.tripsRtoC, 2)} trips to commerce, ${fmt(dev * T.tripsRtoI, 2)} to industry`);
  } else {
    html += row(`Time to homes ${fmt(timeVia(d.toR))} (limit ${T.commuteMax})`);
    if (zone === ZONE_I && dev > 0) html += row(`Sends ${fmt(dev * T.tripsItoC, 2)} trips to commerce (${fmt(timeVia(d.toC))} away)`);
    if (zone === ZONE_C) html += row('Sends no trips (destination only)', '#999');
  }

  // The growth multipliers ZoneGrowthSystem applies from traffic.
  const { width, height } = world.grid;
  let maxCong = 0, hasRoad = false;
  for (let k = 0; k < 4; k++) {
    const ri = neighbourIndex(i, k, width, height);
    if (ri < 0) continue;
    const rc = L.roadClass[ri];
    if (rc === ROAD_NONE || rc === ROAD_HIGHWAY) continue;
    hasRoad = true;
    if (L.congestion[ri] > maxCong) maxCong = L.congestion[ri];
  }
  if (!hasRoad) return html + row('No street or avenue next to this lot', '#e95');
  const accessMult = dev > 0 ? T.accessFloor + (1 - T.accessFloor) * (access / 255) : 1;
  const congMult = 1 - (maxCong / 255) * T.congestionGrowthPenalty;
  html += row(`Growth ×${accessMult.toFixed(2)} from commute, ×${congMult.toFixed(2)} from congestion`);
  return html;
}

export interface TrafficTotals {
  roads: number;          // road tiles
  usedPct: number;        // % of road tiles carrying any traffic
  overPct: number;        // % of road tiles over capacity
  worstRatio: number;     // highest volume / capacity
  trips: number;          // trips generated by all origins that can reach a destination
  homes: number;          // developed, non-abandoned home tiles
  avgCommute: number;     // mean travel time of homes that can reach a destination
  cutOffPct: number;      // % of homes with no reachable commerce or industry
  overLimitPct: number;   // % of homes at or beyond commuteMax (but connected)
}

/** City-wide traffic figures from the last pass, or null before the first one. */
export function trafficTotals(world: World): TrafficTotals | null {
  const d = world.traffic;
  if (!d) return null;
  const L = world.layers;
  const T = BALANCE.transit;
  const n = L.zone.length;

  let roads = 0, used = 0, over = 0, worst = 0;
  let trips = 0, homes = 0, reach = 0, commuteSum = 0, overLimit = 0;
  for (let i = 0; i < n; i++) {
    const rc = L.roadClass[i];
    if (rc !== ROAD_NONE) {
      roads++;
      const ratio = trafficVolume(d, i) / roadCapacity(rc);
      if (ratio > 0) used++;
      if (ratio > 1) over++;
      if (ratio > worst) worst = ratio;
      continue;
    }
    const zone = L.zone[i], dev = L.devLevel[i];
    if (zone === ZONE_NONE || dev === 0 || L.abandoned[i] !== 0) continue;
    const rC = bestAccessRoad(world, i, d.toC);
    const tC = rC >= 0 ? d.toC.dist[rC] : Infinity;
    if (zone === ZONE_R) {
      const rI = bestAccessRoad(world, i, d.toI);
      const tI = rI >= 0 ? d.toI.dist[rI] : Infinity;
      if (tC < Infinity) trips += dev * T.tripsRtoC;
      if (tI < Infinity) trips += dev * T.tripsRtoI;
      homes++;
      const t = Math.min(tC, tI);
      if (t < Infinity) { reach++; commuteSum += t; if (t >= T.commuteMax) overLimit++; }
    } else if (zone === ZONE_I && tC < Infinity) {
      trips += dev * T.tripsItoC;
    }
  }
  const pct = (a: number, b: number) => (b > 0 ? a / b * 100 : 0);
  return {
    roads, usedPct: pct(used, roads), overPct: pct(over, roads), worstRatio: worst,
    trips, homes, avgCommute: reach > 0 ? commuteSum / reach : 0,
    cutOffPct: pct(homes - reach, homes), overLimitPct: pct(overLimit, homes),
  };
}
