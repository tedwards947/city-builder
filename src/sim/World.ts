/** Political state that is not the PC balance itself (that is `budget.politicalCapital`). Saved. */
export interface Politics {
  /**
   * The highest population the city has been credited for. Population
   * milestones pay out only for thresholds above it, then raise it, so each
   * fires once however the population moves or the list of thresholds changes.
   */
  peakPopulation: number;
  /**
   * The change passive regeneration made to PC on the last tick: positive
   * while gaining, negative while draining, 0 at the cap. For the HUD.
   */
  regen: number;
  /**
   * Enacted ordinances (ids from src/sim/ordinances.ts), in the order they
   * were enacted, and which of them are suspended because PC is 0 or below.
   */
  ordinances: { active: string[]; suspended: string[] };
  /**
   * Per request kind, the tick before which it will not be asked again: set
   * when a once-only kind is met (to a tick that never comes) or when a kind
   * with a cooldown expires. A kind not listed can ask at any time.
   */
  requestNotBefore: Record<string, number>;
  /** Open resident requests (src/sim/requests.ts) and the id the next one gets. */
  requests: OpenRequest[];
  nextRequestId: number;
}

